// True service-role client: never reads the visitor's cookies, so it always bypasses RLS.
// createAdminClient() above forwards the visitor's session cookies, which makes it act as
// THAT USER (RLS still applies) whenever a session exists. Use this one for server-side writes
// to tables users must not write directly (orders, squads, quotas, commissions...), and only
// AFTER the route has done its own authn/authz check.
export function createServiceClient() {
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY
  if (!key) throw new Error('SUPABASE_SERVICE_ROLE_KEY is not configured')
  return createSupabaseClient(process.env.NEXT_PUBLIC_SUPABASE_URL!, key, {
    auth: { persistSession: false, autoRefreshToken: false },
  })
}
